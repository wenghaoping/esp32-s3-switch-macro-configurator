import { gzipSync } from "node:zlib";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join, relative } from "node:path";

const [sourceDirectory, outputDirectory] = process.argv.slice(2);
if (!sourceDirectory || !outputDirectory) {
  throw new Error("Usage: node scripts/embed-web-assets.mjs <dist> <output-dir>");
}

const mimeTypeFor = (file) => {
  if (file.endsWith(".html")) return "text/html; charset=utf-8";
  if (file.endsWith(".js")) return "text/javascript; charset=utf-8";
  if (file.endsWith(".css")) return "text/css; charset=utf-8";
  if (file.endsWith(".svg")) return "image/svg+xml";
  if (file.endsWith(".png")) return "image/png";
  if (file.endsWith(".jpg") || file.endsWith(".jpeg")) return "image/jpeg";
  if (file.endsWith(".ico")) return "image/x-icon";
  return "application/octet-stream";
};

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}

const files = (await walk(sourceDirectory)).sort();
const assets = [];
for (const file of files) {
  const path = `/${relative(sourceDirectory, file).replaceAll("\\\\", "/")}`;
  assets.push({ path, mime: mimeTypeFor(file), data: gzipSync(await readFile(file), { level: 9 }) });
}

const byteList = (data) => Array.from(data, (byte) => `0x${byte.toString(16).padStart(2, "0")}`)
  .reduce((lines, byte, index) => {
    const line = Math.floor(index / 16);
    lines[line] = `${lines[line] || "  "}${byte}, `;
    return lines;
  }, []).join("\n");

const blocks = assets.map((asset, index) => `
inline const uint8_t kEmbeddedWebAsset${index}[] PROGMEM = {
${byteList(asset.data)}
};`).join("\n");
const records = assets.map((asset, index) =>
  `  {"${asset.path}", "${asset.mime}", kEmbeddedWebAsset${index}, sizeof(kEmbeddedWebAsset${index})},`,
).join("\n");

const header = `// Generated by scripts/embed-web-assets.mjs. Do not edit.\n#pragma once\n\n#include <Arduino.h>\n\nstruct EmbeddedWebAsset {\n  const char* path;\n  const char* contentType;\n  const uint8_t* data;\n  size_t size;\n};\n${blocks}\n\ninline const EmbeddedWebAsset kEmbeddedWebAssets[] = {\n${records}\n};\ninline constexpr size_t kEmbeddedWebAssetCount = sizeof(kEmbeddedWebAssets) / sizeof(kEmbeddedWebAssets[0]);\n`;

await mkdir(outputDirectory, { recursive: true });
await writeFile(join(outputDirectory, "EmbeddedWebAssets.h"), header);
console.log(`Embedded ${assets.length} web assets (${assets.reduce((total, asset) => total + asset.data.length, 0)} gzip bytes).`);
